"""Generate sim/models/so101/peel_scene.xml: the apple-on-needle scene plus what the peeling task needs.

- needle on a passive turntable (hinge about z with friction, no motor): the robot turns it by gripping the apple
- apple = flesh-coloured collision sphere covered by visual-only skin patches (lat/lon grid); the task hides a
  patch (rgba alpha 0) when the peeler blade passes over it (MuJoCo cannot cut, so peeling is a rule, like the weld)
- peeler (handle + blade) resting on two pegs so the tilted gripper can pinch the handle above the table

Usage: python build_peel_scene.py
"""
from pathlib import Path

import mujoco
import numpy as np

OUT = Path(__file__).resolve().parent / "models/so101/peel_scene.xml"

APPLE_R = 0.04
LAT_STEP, N_LON = 20, 16                # skin grid: rows every 20 deg, 16 columns
PEEL_LAT = 60                           # rows with |lat| <= 60 deg are peelable (poles: stem / needle side)
SKIN_T = 0.0012                         # patch half-thickness, centred SKIN_T outside the flesh
NEEDLE_XY = (0.20, 0.15)
PEELER_XY = (0.20, -0.15)                # handle centre; handle along world y, blade end towards -y (towards the
                                        # robot's right): so it sits in the hand with the T blade able to stay level
                                        # during a vertical stroke (sim/probe_tpeeler_grip.py)
HANDLE_Z = 0.04                         # handle axis height (same as the apple centre the grasp was designed for)
TURN_FRICTION = 0.05                    # turntable dry friction [N m]

SKIN_RGBA = "0.75 0.08 0.08 1"
FLESH_RGBA = "0.96 0.90 0.62 1"


def frame_quat(lat, lon):
    """Quaternion of the local frame x=east, y=north, z=outward normal at (lat, lon) [rad]."""
    n = np.array([np.cos(lat) * np.cos(lon), np.cos(lat) * np.sin(lon), np.sin(lat)])
    e = np.array([-np.sin(lon), np.cos(lon), 0.0])
    q = np.zeros(4)
    mujoco.mju_mat2Quat(q, np.column_stack([e, np.cross(n, e), n]).ravel())
    return n, q


def skin_geoms():
    lines, dlon = [], 2 * np.pi / N_LON
    for i, lat_deg in enumerate(range(-90 + LAT_STEP // 2, 90, LAT_STEP)):
        lat = np.radians(lat_deg)
        for j in range(N_LON):
            lon = (j + 0.5) * dlon
            n, q = frame_quat(lat, lon)
            pos = (APPLE_R + SKIN_T) * n
            a = 0.85 * APPLE_R * np.cos(lat) * dlon
            b = 0.85 * APPLE_R * np.radians(LAT_STEP)
            kind = "skin" if abs(lat_deg) <= PEEL_LAT else "cap"
            lines.append(
                f'      <geom name="{kind}_{i}_{j}" type="ellipsoid" size="{a:.5f} {b:.5f} {SKIN_T:.5f}" '
                f'pos="{pos[0]:.5f} {pos[1]:.5f} {pos[2]:.5f}" quat="{q[0]:.5f} {q[1]:.5f} {q[2]:.5f} {q[3]:.5f}" '
                f'rgba="{SKIN_RGBA}" contype="0" conaffinity="0" density="0"/>')
    for name, z in (("cap_top", 1), ("cap_bottom", -1)):
        lines.append(f'      <geom name="{name}" type="ellipsoid" size="0.013 0.013 {SKIN_T:.5f}" '
                     f'pos="0 0 {z * (APPLE_R + SKIN_T - 0.002):.5f}" rgba="{SKIN_RGBA}" contype="0" conaffinity="0" density="0"/>')
    return "\n".join(lines)


XML = f"""<!--
  GENERATED by sim/build_peel_scene.py - edit that script, not this file.
  Apple peeling task scene for SO101 (MuJoCo). Same frame / collision bits as apple_scene.xml, plus:
  peeler contype=8 conaffinity=1 -> collides with robot and table, NOT with the apple (peeling is a rule) or the needle.
-->
<mujoco model="so101_apple_peel">
  <include file="so101_new_calib_camera.xml"/>

  <option timestep="0.0016666666666666668" cone="elliptic" impratio="10" noslip_iterations="5"/>

  <visual>
    <headlight diffuse="0.5 0.5 0.5" ambient="0.3 0.3 0.3" specular="0 0 0"/>
    <global offwidth="640" offheight="480" azimuth="160" elevation="-25"/>
  </visual>

  <asset>
    <texture type="skybox" builtin="gradient" rgb1="0.6 0.7 0.8" rgb2="0.2 0.2 0.25" width="512" height="3072"/>
    <texture name="wood" type="2d" builtin="flat" rgb1="0.62 0.47 0.32" width="64" height="64"/>
    <material name="table" texture="wood" rgba="1 1 1 1"/>
    <material name="floor" rgba="0.3 0.3 0.32 1"/>
    <material name="steel" rgba="0.8 0.8 0.85 1" specular="0.9" shininess="0.9"/>
    <material name="stand" rgba="0.15 0.15 0.15 1"/>
    <material name="handle" rgba="0.1 0.45 0.2 1"/>
  </asset>

  <worldbody>
    <!-- no shadows: WSL renders in software and the shadow pass is 2/3 of the render time (282 -> 93 ms per camera) -->
    <light name="key" pos="0.3 -0.3 1.2" dir="-0.2 0.2 -1" directional="true" diffuse="0.7 0.7 0.7" castshadow="false"/>
    <geom name="floor" type="plane" size="0 0 0.05" pos="0 0 -0.75" material="floor"/>
    <geom name="table" type="box" size="0.35 0.45 0.02" pos="0.15 0 -0.02" material="table" friction="1 0.005 0.0001"/>

    <body name="workspace_center" pos="0.2 0 0"/>
    <camera name="overhead" mode="targetbody" target="workspace_center" pos="0.55 0 0.55" fovy="60"/>

    <body name="apple" pos="0.26 0.03 0.04">
      <freejoint name="apple_free"/>
      <geom name="apple" type="sphere" size="{APPLE_R}" mass="0.2" rgba="{FLESH_RGBA}"
            contype="2" conaffinity="1" condim="4" friction="1.5 0.02 0.001" solref="0.004 1"/>
      <geom name="apple_stem" type="capsule" fromto="0 0 0.038 0.003 0 0.054" size="0.002"
            rgba="0.35 0.22 0.1 1" contype="0" conaffinity="0" density="0"/>
{skin_geoms()}
    </body>



    <!-- passive turntable: the needle stand rotates about z (friction holds it still unless the robot turns the apple);
         white marker shows the angle in the camera images -->
    <body name="needle" pos="{NEEDLE_XY[0]} {NEEDLE_XY[1]} 0">
      <joint name="turntable" type="hinge" axis="0 0 1" damping="0.05" frictionloss="{TURN_FRICTION}" armature="0.001"/>
      <geom name="needle_stand" type="cylinder" size="0.03 0.01" pos="0 0 0.01" material="stand"/>
      <geom name="turntable_marker" type="box" size="0.012 0.003 0.0006" pos="0.016 0 0.0201" rgba="1 1 1 1"
            contype="0" conaffinity="0" density="0"/>
      <geom name="needle_shaft" type="cylinder" size="0.0025 0.04" pos="0 0 0.06" material="steel"
            contype="4" conaffinity="1"/>
      <site name="needle_tip" pos="0 0 0.1" size="0.003" rgba="1 0 0 1"/>
    </body>

    <!-- peeler rests on two pegs; handle along world y, blade end towards -y. Pegs are 44 mm deep in x so a peeler
         put back a few mm off (and rolled in the grip) still lands on them -->
    <geom name="peg_a" type="box" size="0.022 0.008 {(HANDLE_Z - 0.006) / 2:.4f}" pos="{PEELER_XY[0]} {PEELER_XY[1] - 0.04} {(HANDLE_Z - 0.006) / 2:.4f}" material="stand"/>
    <geom name="peg_b" type="box" size="0.022 0.008 {(HANDLE_Z - 0.006) / 2:.4f}" pos="{PEELER_XY[0]} {PEELER_XY[1] + 0.04} {(HANDLE_Z - 0.006) / 2:.4f}" material="stand"/>
    <body name="peeler" pos="{PEELER_XY[0]} {PEELER_XY[1]} {HANDLE_Z}" quat="0.70711 0 0 -0.70711">
      <freejoint name="peeler_free"/>
      <!-- stiff contact (like the apple): with the default solref the squeezed handle sank ~8 mm into the fingers -->
      <geom name="peeler_handle" type="box" size="0.05 0.007 0.006" mass="0.03" material="handle"
            contype="8" conaffinity="1" condim="4" friction="1.5 0.02 0.001" solref="0.004 1"/>
      <geom name="peeler_prong_a" type="box" size="0.010 0.002 0.003" pos="0.060 -0.020 0" material="steel"
            contype="8" conaffinity="1" mass="0.003"/>
      <geom name="peeler_prong_b" type="box" size="0.010 0.002 0.003" pos="0.060 0.020 0" material="steel"
            contype="8" conaffinity="1" mass="0.003"/>
      <geom name="peeler_blade" type="capsule" fromto="0.07 -0.018 0 0.07 0.018 0" size="0.0015" material="steel"
            contype="0" conaffinity="0" density="0"/>
      <site name="peeler_blade" pos="0.07 0 0" size="0.003" rgba="0 0 1 1" group="3"/>
      <site name="peeler_grip" pos="-0.015 0 0" size="0.003" rgba="0 1 1 1" group="3"/>
    </body>
  </worldbody>

  <equality>
    <weld name="apple_on_needle" body1="needle" body2="apple" active="false" solref="0.005 1"/>
  </equality>
</mujoco>
"""

if __name__ == "__main__":
    OUT.write_text(XML)
    m = mujoco.MjModel.from_xml_path(str(OUT))
    n_skin = sum(m.geom(i).name.startswith("skin_") for i in range(m.ngeom))
    print(f"wrote {OUT}: ngeom={m.ngeom} skin patches={n_skin} nu={m.nu}")
